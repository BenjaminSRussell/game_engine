void mesh_calculate_normals(mesh_t* mesh) {
    if (!mesh || !mesh->vertices || !mesh->indices) return;

    // Reset normals
    for (u32 i = 0; i < mesh->vertex_count; ++i) {
        mesh->vertices[i].normal = (Vec3){0, 0, 0};
    }

    // Iterate triangles
    for (u32 i = 0; i < mesh->index_count; i += 3) {
        u32 i0 = mesh->indices[i];
        u32 i1 = mesh->indices[i + 1];
        u32 i2 = mesh->indices[i + 2];

        Vec3 v0 = mesh->vertices[i0].position;
        Vec3 v1 = mesh->vertices[i1].position;
        Vec3 v2 = mesh->vertices[i2].position;

        Vec3 edge1 = vec3_sub(v1, v0);
        Vec3 edge2 = vec3_sub(v2, v0);

        // Cross product is area weighted, so don't normalize yet
        Vec3 normal = vec3_cross(edge1, edge2);

        // Accumulate
        mesh->vertices[i0].normal = vec3_add(mesh->vertices[i0].normal, normal);
        mesh->vertices[i1].normal = vec3_add(mesh->vertices[i1].normal, normal);
        mesh->vertices[i2].normal = vec3_add(mesh->vertices[i2].normal, normal);
    }

    // Normalize result
    for (u32 i = 0; i < mesh->vertex_count; ++i) {
        mesh->vertices[i].normal = vec3_normalize(mesh->vertices[i].normal);
    }
}

