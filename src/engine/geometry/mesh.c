void mesh_add_submesh(mesh_t* mesh, submesh_t submesh) {
    if (!mesh) return;
    
    // Very simple dynamic array for submeshes
    u32 new_count = mesh->submesh_count + 1;
    submesh_t* new_submeshes = (submesh_t*)MALLOC_GEOMETRY(sizeof(submesh_t) * new_count);
    
    if (mesh->submeshes) {
        memcpy(new_submeshes, mesh->submeshes, sizeof(submesh_t) * mesh->submesh_count);
        FREE(mesh->submeshes);
    }
    
    new_submeshes[mesh->submesh_count] = submesh;
    mesh->submeshes = new_submeshes;
    mesh->submesh_count = new_count;
}

void mesh_clear_submeshes(mesh_t* mesh) {
    if (!mesh) return;
    if (mesh->submeshes) {
        FREE(mesh->submeshes);
    }
    mesh->submeshes = 0;
    mesh->submesh_count = 0;
}

void mesh_set_material(mesh_t* mesh, u32 slot, u32 material_id) {
    if (!mesh) return;
    if (slot >= MESH_MAX_MATERIALS) {
        LOG_ERROR("mesh_set_material: Slot %d out of bounds (Max %d)", slot, MESH_MAX_MATERIALS);
        return;
    }
    mesh->material_ids[slot] = material_id;
    if (slot >= mesh->material_count) {
        mesh->material_count = slot + 1;
    }
}

