void mesh_calculate_bounds(mesh_t* mesh) {
    if (!mesh || mesh->vertex_count == 0) {
        memset(&mesh->bounds, 0, sizeof(mesh_bounds_t));
        return;
    }

    Vec3 min = {FLT_MAX, FLT_MAX, FLT_MAX};
    Vec3 max = {-FLT_MAX, -FLT_MAX, -FLT_MAX};

    for (u32 i = 0; i < mesh->vertex_count; ++i) {
        Vec3 p = mesh->vertices[i].position;
        if (p.x < min.x) min.x = p.x;
        if (p.y < min.y) min.y = p.y;
        if (p.z < min.z) min.z = p.z;
        
        if (p.x > max.x) max.x = p.x;
        if (p.y > max.y) max.y = p.y;
        if (p.z > max.z) max.z = p.z;
    }

    mesh->bounds.min = min;
    mesh->bounds.max = max;

    // Calculate center and radius
    Vec3 center = vec3_add(min, max);
    mesh->bounds.sphere_center = vec3_mul(center, 0.5f);
    
    f32 max_dist_sq = 0.0f;
    for (u32 i = 0; i < mesh->vertex_count; ++i) {
        Vec3 p = mesh->vertices[i].position;
        f32 dist_sq = vec3_distance_sq(p, mesh->bounds.sphere_center);
        if (dist_sq > max_dist_sq) {
            max_dist_sq = dist_sq;
        }
    }
    mesh->bounds.sphere_radius = sqrtf(max_dist_sq);
}

