mesh_t* mesh_create(const char* name) {
    mesh_t* mesh = (mesh_t*)MALLOC_GEOMETRY(sizeof(mesh_t));
    memset(mesh, 0, sizeof(mesh_t));
    
    if (name) {
        strncpy(mesh->name, name, 63);
        mesh->name[63] = '\0';
    } else {
        strncpy(mesh->name, "unnamed_mesh", 63);
    }
    
    // Default ID (Should be generated by a resource manager)
    static u32 geometry_id_counter = 0;
    mesh->id = ++geometry_id_counter;
    
    mesh->ref_count = 1;
    mesh->flags = MESH_FLAG_NONE;

    return mesh;
}

void mesh_destroy(mesh_t* mesh) {
    if (!mesh) return;
    
    mesh->ref_count--;
    if (mesh->ref_count > 0) return;

    // TODO: Release GPU resources
    // if (mesh->vertex_buffer_handle != 0) gpu_free_buffer(mesh->vertex_buffer_handle);
    // if (mesh->index_buffer_handle != 0) gpu_free_buffer(mesh->index_buffer_handle);

    if (mesh->vertices) {
        FREE(mesh->vertices);
    }

    if (mesh->indices) {
        FREE(mesh->indices);
    }

    if (mesh->submeshes) {
        FREE(mesh->submeshes);
    }

    FREE(mesh);
}

// ----------------------------------------------------------------------------
// Buffer Management
// ----------------------------------------------------------------------------

void mesh_allocate_buffers(mesh_t* mesh, u32 vertex_count, u32 index_count) {
    if (!mesh) return;

    if (mesh->vertices) {
        FREE(mesh->vertices);
    }
    
    if (mesh->indices) {
        FREE(mesh->indices);
    }

    mesh->vertex_capacity = vertex_count;
    mesh->index_capacity = index_count;
    mesh->vertex_count = 0;
    mesh->index_count = 0;

    if (vertex_count > 0) {
        mesh->vertices = (vertex_t*)MALLOC_GEOMETRY(sizeof(vertex_t) * vertex_count);
    }
    
    if (index_count > 0) {
        mesh->indices = (u32*)MALLOC_GEOMETRY(sizeof(u32) * index_count);
    }
}

void mesh_set_vertices(mesh_t* mesh, const vertex_t* vertices, u32 count, u32 offset) {
    if (!mesh || !vertices) return;
    if (offset + count > mesh->vertex_capacity) {
        LOG_ERROR("mesh_set_vertices: Out of bounds. Capacity: %d, Request: %d", mesh->vertex_capacity, offset + count);
        return;
    }

    memcpy(mesh->vertices + offset, vertices, sizeof(vertex_t) * count);
    if (offset + count > mesh->vertex_count) {
        mesh->vertex_count = offset + count;
    }
    
    mesh->flags |= MESH_FLAG_DYNAMIC; // Mark as dirty/dynamic if updated
}

void mesh_set_indices(mesh_t* mesh, const u32* indices, u32 count, u32 offset) {
    if (!mesh || !indices) return;
    if (offset + count > mesh->index_capacity) {
        LOG_ERROR("mesh_set_indices: Out of bounds. Capacity: %d, Request: %d", mesh->index_capacity, offset + count);
        return;
    }

    memcpy(mesh->indices + offset, indices, sizeof(u32) * count);
    if (offset + count > mesh->index_count) {
        mesh->index_count = offset + count;
    }
}

